// InitPlaceholderModel is the placeholder model id init writes.
const InitPlaceholderModel = "openai/gpt-4o-mini"

// The `.docsync/` files init writes (config root; all PR-reviewed, human-owned).
var initFiles = []string{"manifest.yml", "models.yml", "instructions.md"}

// initManifestContent is the skeleton init writes for manifest.yml.
const initManifestContent = `# docSync manifest (generated by 'docsync init' — P7-T01, OD-R15).
# Schema authority stays with the Phase 0 loader; this skeleton is the minimal
# valid shape. Replace the example entry with your real documentation allowlist.
version: 1
documents:
  # 'path' is the documentation file, 'sources' are the code globs whose
  # changes can make it stale, 'triggers' filter which kinds of changes count.
  - path: docs/README.md
    mode: suggest
    sources:
      - "src/**"
    triggers:
      - public_behavior
`

