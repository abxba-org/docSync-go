// Ported from packages/cli/src/commands/init.ts (P7-T01; OD-R15 — recommended
// default ADOPTED: a thin, deterministic scaffolding command; schema authority
// stays with the Phase-0 loader, init only produces a skeleton that the loader
// accepts).
//
// Contract (V-P7 init gate):
//   - writes exactly the minimal Phase-0 config: manifest.yml, models.yml,
//     instructions.md (policy.yml/concepts.yml are optional in the layout);
//   - never silently overwrites existing files — without --force an existing
//     valid config is a no-op (idempotent, exit 0) and an existing INVALID one
//     is exit 2 with its diagnostics (fail-closed);
//   - validates what it wrote with ValidateRepositoryConfig and NEVER exits 0
//     with an invalid skeleton (init is fail-closed, D8);
//   - models.yml placeholders satisfy the gateway structural gate
//     (ParseModelsConfig / EXTENDED_MODELS_SCHEMA) and carry the comment that
//     OPENROUTER_API_KEY is env-only (§3 rule 8: models never hold credentials).
package cli

import (
	"os"
	"path/filepath"

	"github.com/DUDE616/docSync-go/internal/schemas"
	"github.com/DUDE616/docSync-go/internal/validate"
)

// InitOptions configures RunInit.
type InitOptions struct {
	// RepoRoot is the absolute repository root.
	RepoRoot string
	// Force overwrites existing config files (still re-validated after writing).
	Force bool
}

// InitResult is the init outcome (exit code + human messages).
type InitResult struct {
	ExitCode DocsyncExitCode
	Messages []string
}

