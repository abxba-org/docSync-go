package gitpr

// Ported from packages/core/src/gitpr/pr-body.ts (P6-T03; ARCH §12.1 parity
// contract applied to the PR surface; P19 — NO LLM anywhere).
//
// Deterministic markdown built ONLY from the frozen RunOutcome and the canonical
// report (rows are CONSUMED, never re-derived; D3-pinned confidence displays, D5
// routed-model bindings and D7 unknown-coverage data all arrive pre-derived).
// Same inputs → byte-identical body; no clocks, no I/O, no model calls — a
// reviewer reads what the run actually decided, in the canonical view.
//
// Sections: (a) banner; (b) provenance summary (run id, policy version, routed
// model bindings); (c) candidate mapping table (doc → outcome, confidence,
// evidence); (d) verification results (verdict + auto-eligibility per doc);
// (e) abstains/findings/degradations; (f) unknown-coverage note (D7) when
// present.

import (
	"regexp"
	"strconv"
	"strings"

	"github.com/DUDE616/docSync-go/internal/schemas"
)

// PRBodyBanner is the one-line review banner (first line of every doc PR body).
const PRBodyBanner = "> generated by docsync — review like any code change"

// RenderPrBodyInput is the render input — canonical report + the frozen
// outcome.
type RenderPrBodyInput struct {
	Outcome schemas.RunOutcome
	Report  schemas.CanonicalReport
	// SourcePR is the source PR number, rendered as `Source PR: #<n>` when
	// present (0 ⇒ absent).
	SourcePR int
}

// prBodyCell is the markdown-table cell renderer: escape pipes + collapse line
// breaks (data stays data).
func prBodyCell(value string) string {
	return prBodyLineBreaks.ReplaceAllString(strings.ReplaceAll(value, "|", `\|`), " ")
}

// prBodyLineBreaks matches one run of CR/LF characters (TS /[\r\n]+/g).
var prBodyLineBreaks = regexp.MustCompile(`[\r\n]+`)

// describeBinding is the D5 canonical view of one binding: role `model`
// (provider `provider`).
func describeBinding(binding schemas.RunModelBinding) string {
	provider := ""
	if binding.Provider != nil {
		provider = " (provider `" + *binding.Provider + "`)"
	}
	return binding.Role + " `" + binding.Model + "`" + provider
}

// RenderPrBody renders the PR body (P6-T03). Pure and deterministic — NO LLM
// anywhere: a pure function of the outcome/canonical report (P19).
func RenderPrBody(input RenderPrBodyInput) string {
	var lines []string

	// (a) banner
	lines = append(lines, PRBodyBanner, "")

	// (b) provenance summary (D5 canonical view — routed models, verbatim)
	lines = append(lines, "## Provenance", "")
	lines = append(lines, "- Run: `"+input.Outcome.RunID+"`")
	lines = append(lines, "- Policy: v"+strconv.Itoa(input.Report.PolicyVersion))
	bindings := make([]string, 0, len(input.Report.ModelBindings))
	for _, binding := range input.Report.ModelBindings {
		bindings = append(bindings, describeBinding(binding))
	}
	lines = append(lines, "- Models: "+strings.Join(bindings, " · "))
	if input.SourcePR != 0 {
		lines = append(lines, "- Source PR: #"+strconv.Itoa(input.SourcePR))
	}
	lines = append(lines, "")

	// (c) candidate mapping table (report rows + evidence — CONSUMED, not re-derived)
	lines = append(lines, "## Documentation mapping", "")
	lines = append(lines, "| Document | Outcome | Confidence | Evidence |")
	lines = append(lines, "| --- | --- | --- | --- |")
	for _, row := range input.Report.Rows {
		confidence := "—"
		if row.ConfidenceDisplay != nil {
			confidence = *row.ConfidenceDisplay
		}
		lines = append(lines,
			"| "+prBodyCell(row.DocPath)+" | "+prBodyCell(string(row.Outcome))+" | "+
				prBodyCell(confidence)+" | "+prBodyCell(strings.Join(row.Evidence, ", "))+" |")
	}
	lines = append(lines, "")

	// (d) verification results (verdict + auto-eligibility per doc, from the outcome)
	lines = append(lines, "## Verification", "")
	lines = append(lines, "| Document | Verdict | Auto-eligible |")
	lines = append(lines, "| --- | --- | --- |")
	for _, doc := range input.Outcome.Documents {
		verdict := "—"
		autoEligible := "—"
		if doc.Verification != nil {
			verdict = string(doc.Verification.Verdict)
			autoEligible = "no"
			if doc.Verification.AutoEligible {
				autoEligible = "yes"
			}
		}
		lines = append(lines,
			"| "+prBodyCell(doc.DocPath)+" | "+prBodyCell(verdict)+" | "+autoEligible+" |")
	}
	lines = append(lines, "")

	// (e) abstains / findings / degradations — always rendered, explicit when empty
	lines = append(lines, "## Abstains", "")
	if len(input.Report.Abstains) == 0 {
		lines = append(lines, "None.")
	} else {
		for _, abstain := range input.Report.Abstains {
			docPath := "(run)"
			if abstain.DocPath != nil {
				docPath = *abstain.DocPath
			}
			lines = append(lines,
				"- `"+abstain.AbstainID+"` "+docPath+" — "+abstain.Reason+" — "+abstain.Detail)
		}
	}
	lines = append(lines, "")
	lines = append(lines, "## Findings", "")
	if len(input.Report.Findings) == 0 {
		lines = append(lines, "None.")
	} else {
		for _, finding := range input.Report.Findings {
			docPath := "(run)"
			if finding.DocPath != nil {
				docPath = *finding.DocPath
			}
			lines = append(lines, "- "+docPath+" — "+finding.Kind+" — "+finding.Detail)
		}
	}
	lines = append(lines, "")
	lines = append(lines, "## Degradations", "")
	if len(input.Report.Degradations) == 0 {
		lines = append(lines, "None.")
	} else {
		for _, degradation := range input.Report.Degradations {
			lines = append(lines,
				"- "+degradation.Stage+" — "+string(degradation.Kind)+" — "+degradation.Detail)
		}
	}
	lines = append(lines, "")

	// (f) unknown coverage (D7) — surfaced, never silenced, only when present
	if len(input.Report.UnknownCoverage) > 0 {
		lines = append(lines, "## Unknown coverage (D7)", "")
		for _, path := range input.Report.UnknownCoverage {
			lines = append(lines, "- "+path)
		}
		lines = append(lines, "")
	}

	return strings.TrimRight(strings.Join(lines, "\n"), " \t\r\n") + "\n"
}
