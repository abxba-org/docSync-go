func TestV_P9_5_ConfidenceIsRenderedWithTwoDecimals(t *testing.T) {
	// toFixed(2) parity: 0.9 ⇒ "0.90".
	body := provenance.RenderProvenanceSummary(*buildRecord(t, func(in *provenance.BuildProvenanceInput) {
		*in = docPrProvenanceInput()
	}))
	assert.Contains(t, body, "- Run: `run_flow_01J`")
	assert.Contains(t, body, "confidence 0.90) · writer `anthropic/claude-sonnet-4.5`")
	assert.Contains(t, body, "- Generated: 2026-10-07T00:00:00.000Z")
	assert.Contains(t, body, "| src/payments/refund.ts |")
}

func TestRenderProvenanceSummary_EscapesTableCells(t *testing.T) {
	// Markdown-table cell: escape pipes + collapse line breaks (data stays data).
	body := provenance.RenderProvenanceSummary(*buildRecord(t, func(in *provenance.BuildProvenanceInput) {
		in.SourceFiles = []string{"src/a|b\nc.ts", "src/plain.ts"}
	}))
	assert.Contains(t, body, "| src/a\\|b c.ts |")
	assert.Contains(t, body, "| src/plain.ts |")
	// The escaped cell never leaks a raw line break into the table.
	assert.NotContains(t, body, "b\nc.ts")
}

func TestRenderProvenanceSummary_OverEveryVerdict(t *testing.T) {
	for _, verdict := range []string{"pass", "review", "reject"} {
		body := provenance.RenderProvenanceSummary(*buildRecord(t, func(in *provenance.BuildProvenanceInput) {
			in.VerificationStatus = verdict
		}))
		assert.Contains(t, body, "- Status: `"+verdict+"`")
	}
}

