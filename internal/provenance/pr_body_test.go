// docPrProvenanceInput mirrors the doc-pr-provenance fixture's buildProvenanceRecord
// call (RUN_ID run_flow_01J, confidence 0.9, the same routed models).
func docPrProvenanceInput() provenance.BuildProvenanceInput {
	return validInput(func(in *provenance.BuildProvenanceInput) {
		in.RunID = "run_flow_01J"
		in.SourceFiles = []string{"src/payments/refund.ts"}
		in.DetectorConfidence = 0.9
		in.Now = "2026-10-07T00:00:00.000Z"
	})
}

