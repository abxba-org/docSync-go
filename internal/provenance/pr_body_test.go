func TestV_P9_EphemeralCheckRunProjection(t *testing.T) {
	record := buildRecord(t, nil)
	view := provenance.ProjectCheckRunMetadata(*record)

	// The payload is exactly {title, summary, text} — nothing more.
	fields := reflect.TypeOf(view)
	require.Equal(t, reflect.Struct, fields.Kind())
	assert.Equal(t, 3, fields.NumField())

	assert.Equal(t, "docsync provenance: run "+record.RunID+" (ephemeral view)", view.Title)
	assert.Contains(t, view.Title, "ephemeral view")
	assert.Equal(t, "docsync provenance for run `"+record.RunID+"` — "+provenance.CheckViewEphemeralMarker, view.Summary)
	assert.Contains(t, view.Summary, "ephemeral view")
	assert.Equal(t, expectedCheckRunText, view.Text)

	assert.Contains(t, view.Text, "ephemeral view")
	assert.Contains(t, view.Text, record.RunID)
	assert.Contains(t, view.Text, record.SourceCommit)
	assert.Contains(t, view.Text, "`pass`")
	assert.Contains(t, view.Text, record.Detector.Model)

	// Deterministic projection.
	assert.Equal(t, view.Text, provenance.ProjectCheckRunMetadata(*record).Text)
	assert.Equal(t, view, provenance.ProjectCheckRunMetadata(*record))
}

func TestProjectCheckRunMetadata_ProjectionOnlyEchoesTheRecord(t *testing.T) {
	// Every value in the payload is derived from the record: the marker is the
	// only constant, and it is the D5 ephemeral note by contract.
	record := buildRecord(t, func(in *provenance.BuildProvenanceInput) {
		in.VerificationStatus = "review"
	})
	view := provenance.ProjectCheckRunMetadata(*record)
	assert.Contains(t, view.Text, "- Verification: `review`")
	assert.NotContains(t, view.Text, "`pass`")
	assert.Contains(t, view.Text, provenance.CheckViewEphemeralMarker)
}
