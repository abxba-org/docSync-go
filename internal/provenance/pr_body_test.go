// Black-box port of packages/core/test/provenance.test.ts, PR-body and
// check-run halves:
//   - "canonical PR-body summary (P9-T03; D5)" — determinism + every section;
//   - the provenance-package assertions of doc-pr-provenance.test.ts
//     (V-P9-5: the composed doc-PR body carries the canonical record block).
//     The doc-PR flow itself (provenance gate, incident log, zero platform
//     calls) belongs to internal/gitpr and is out of scope for this package;
//     only the record-level rendering it consumes is asserted here.
//   - "ephemeral check-run projection (P9-T05; D5)" — the ephemeral view.
//
// Golden data: the TS *_EXAMPLE values become Go literals asserted byte-for-byte
// through the renderer.

