package provenance

// Ported from core/src/provenance/pr-body.ts (P9-T03; ARCH §12.4/§12.5;
// D5 — the CANONICAL surface). Pure renderer over ONE `docsync.provenance/v1`
// record: docsync block (generated-by banner) + candidate mapping table
// (source files) + verification results + policy/run ids. Deterministic — the
// clock is IN the record (`generated_at`), never read here; same record ⇒
// byte-identical markdown.
//
// Coordination with `renderPrBody` (gitpr/pr-body.ts, P6-T03): that renderer
// owns the RUN-level PR body (RunOutcome + canonical report). This module is
// the RECORD-level canonical block: the D5 archival record rendered for
// review. They deliberately share exactly one banner source —
// `PR_BODY_BANNER` is imported, never duplicated — and the `## Provenance`
// heading. Markdown document bodies are NEVER modified for provenance (D5
// rule 5): this text only ever lands in a PR body, never in a doc.

import (
	"regexp"
	"strconv"
	"strings"

	"github.com/DUDE616/docSync-go/internal/schemas"
)

// PrBodyBanner is the one-line review banner (first line of every doc PR body),
// copied verbatim from gitpr/pr-body.ts's PR_BODY_BANNER — the single banner
// source there. internal/gitpr is not ported yet; when it lands, replace this
// constant with that package's export instead of declaring a second one.
const PrBodyBanner = "> generated by docsync — review like any code change"

// lineBreakRun matches the CR/LF class the TS cell() collapsed.
var lineBreakRun = regexp.MustCompile(`[\r\n]+`)

// cell is the markdown-table cell escaper: escape pipes + collapse line breaks
// (data stays data).
func cell(value string) string {
	return lineBreakRun.ReplaceAllString(strings.ReplaceAll(value, "|", `\|`), " ")
}

// fixed2 ports JS `Number.prototype.toFixed(2)` for the confidence display.
func fixed2(value float64) string {
	return strconv.FormatFloat(value, 'f', 2, 64)
}

// RenderProvenanceSummary renders the canonical D5 provenance block for a PR
// body (P9-T03).
func RenderProvenanceSummary(record schemas.Provenance) string {
	var lines []string

	// docsync block — generated-by banner (single banner source, P6-T03).
	lines = append(lines, PrBodyBanner, "")

	// provenance ids: run, policy, manifest, models (routed, verbatim).
	lines = append(lines, "## Provenance", "")
	lines = append(lines, "- Run: `"+record.RunID+"`")
	lines = append(lines, "- Policy: v"+strconv.Itoa(record.PolicyVersion))
	lines = append(lines, "- Manifest: v"+record.ManifestVersion)
	lines = append(lines, "- Models: detector `"+record.Detector.Model+
		"` (confidence "+fixed2(record.Detector.Confidence)+") · writer `"+record.Writer.Model+"`")
	lines = append(lines, "- Generated: "+record.GeneratedAt)
	lines = append(lines, "")

	// candidate mapping table: source files the run derived the change from.
	lines = append(lines, "## Documentation mapping", "")
	lines = append(lines, "| Source file |")
	lines = append(lines, "| --- |")
	for _, file := range record.SourceFiles {
		lines = append(lines, "| "+cell(file)+" |")
	}
	lines = append(lines, "")

	// verification results line (canonical verifier verdict vocabulary).
	lines = append(lines, "## Verification", "")
	lines = append(lines, "- Status: `"+string(record.Verification.Status)+"`")

	return strings.TrimRightFunc(strings.Join(lines, "\n"), unicodeSpace) + "\n"
}

// unicodeSpace mirrors the JS trimEnd whitespace cutset closely enough for the
// rendered block (the final line never ends in whitespace — the trim is a
// safety net, never the formatter).
func unicodeSpace(r rune) bool {
	return strings.ContainsRune(" \t\r\n\v\f\u00a0\ufeff", r)
}
